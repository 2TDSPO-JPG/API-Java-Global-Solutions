BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'SN_EMAIL_LOGS', 'SN_ALERT_RECIPIENTS', 'SN_NOTIFICATIONS', 'SN_REPORT_HISTORY', 'SN_REPORT_UPDATES', 'SN_REPORTS', 'SN_FILES',
      'SN_SENSOR_EVENTS', 'SN_SENSOR_READINGS', 'SN_SENSORS', 'SN_USERS')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE sn_users (
    id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    full_name       NVARCHAR2(120)  NOT NULL,
    email           NVARCHAR2(160)  NOT NULL,
    password_hash   NVARCHAR2(100)  NOT NULL,
    user_role       NVARCHAR2(20)   NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_sn_users PRIMARY KEY (id),
    CONSTRAINT uk_sn_users_email UNIQUE (email),
    CONSTRAINT ck_sn_users_role CHECK (user_role IN ('RESIDENT', 'OPERATOR', 'ADMIN'))
);

CREATE TABLE sn_sensors (
    id                     NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    prefix                 NVARCHAR2(30)   NOT NULL,
    sensor_name            NVARCHAR2(100)  NOT NULL,
    equipment_type         NVARCHAR2(100)  NOT NULL,
    address                NVARCHAR2(200)  NOT NULL,
    neighborhood           NVARCHAR2(80)   NOT NULL,
    latitude               FLOAT(53)       NOT NULL,
    longitude              FLOAT(53)       NOT NULL,
    capacity_liters        FLOAT(53)       NOT NULL,
    limit_liters           FLOAT(53)       NOT NULL,
    radius_meters          FLOAT(53)       NOT NULL,
    expected_interval_min  NUMBER(10)      NOT NULL,
    current_status         NVARCHAR2(20)   NOT NULL,
    current_volume         FLOAT(53),
    current_level_cm       FLOAT(53),
    last_reading_at        TIMESTAMP(6) WITH TIME ZONE,
    status_reason          NVARCHAR2(255),
    normal_streak          NUMBER(10)      NOT NULL,
    active                 NUMBER(1)       NOT NULL,
    created_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deleted_at             TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_sn_sensors PRIMARY KEY (id),
    CONSTRAINT ck_sn_sensors_status CHECK (current_status IN ('NORMAL', 'WARNING', 'ALARM', 'OFFLINE')),
    CONSTRAINT ck_sn_sensors_limit CHECK (limit_liters > 0 AND limit_liters <= capacity_liters),
    CONSTRAINT ck_sn_sensors_active CHECK (active IN (0, 1))
);
CREATE INDEX ix_sn_sensors_prefix ON sn_sensors (prefix);

CREATE TABLE sn_sensor_readings (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    sensor_id        NUMBER(19)      NOT NULL,
    measured_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    received_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    volume_liters    FLOAT(53)       NOT NULL,
    level_cm         FLOAT(53),
    capacity_liters  FLOAT(53)       NOT NULL,
    limit_liters     FLOAT(53)       NOT NULL,
    reading_status   NVARCHAR2(20)   NOT NULL,
    reading_source   NVARCHAR2(60),
    note             NVARCHAR2(255),
    CONSTRAINT pk_sn_sensor_readings PRIMARY KEY (id),
    CONSTRAINT fk_sn_readings_sensor FOREIGN KEY (sensor_id) REFERENCES sn_sensors (id)
);
CREATE INDEX ix_sn_readings_sensor_time ON sn_sensor_readings (sensor_id, measured_at);

CREATE TABLE sn_sensor_events (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    sensor_id      NUMBER(19)      NOT NULL,
    event_kind     NVARCHAR2(20)   NOT NULL,
    severity       NVARCHAR2(20)   NOT NULL,
    started_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ended_at       TIMESTAMP(6) WITH TIME ZONE,
    event_message  NVARCHAR2(255)  NOT NULL,
    peak_volume    FLOAT(53),
    CONSTRAINT pk_sn_sensor_events PRIMARY KEY (id),
    CONSTRAINT fk_sn_events_sensor FOREIGN KEY (sensor_id) REFERENCES sn_sensors (id)
);
CREATE INDEX ix_sn_events_sensor_start ON sn_sensor_events (sensor_id, started_at);

CREATE TABLE sn_files (
    id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    content_type  NVARCHAR2(100)  NOT NULL,
    file_name     NVARCHAR2(160)  NOT NULL,
    size_bytes    NUMBER(19)      NOT NULL,
    content       BLOB            NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_sn_files PRIMARY KEY (id)
);

CREATE TABLE sn_reports (
    id                       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    protocol                 NVARCHAR2(20)    NOT NULL,
    owner_id                 NUMBER(19)       NOT NULL,
    category                 NVARCHAR2(40)    NOT NULL,
    description              NVARCHAR2(1000)  NOT NULL,
    address                  NVARCHAR2(200)   NOT NULL,
    neighborhood             NVARCHAR2(80)    NOT NULL,
    latitude                 FLOAT(53)        NOT NULL,
    longitude                FLOAT(53)        NOT NULL,
    report_status            NVARCHAR2(20)    NOT NULL,
    sensor_id                NUMBER(19),
    photo_file_id            NUMBER(19),
    previous_report_id       NUMBER(19),
    resolution               NVARCHAR2(600),
    progress_note            NVARCHAR2(600),
    assessment_note          NVARCHAR2(600),
    assessment_requested_at  TIMESTAMP(6) WITH TIME ZONE,
    created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    closed_at                TIMESTAMP(6) WITH TIME ZONE,
    deleted_at               TIMESTAMP(6) WITH TIME ZONE,
    priority_level           NVARCHAR2(20),
    due_at                   TIMESTAMP(6) WITH TIME ZONE,
    assignee_id              NUMBER(19),
    closing_outcome          NVARCHAR2(20),
    reopen_count             NUMBER(10),
    sensor_locked            NUMBER(1),
    CONSTRAINT pk_sn_reports PRIMARY KEY (id),
    CONSTRAINT fk_sn_reports_assignee FOREIGN KEY (assignee_id) REFERENCES sn_users (id),
    CONSTRAINT uk_sn_reports_protocol UNIQUE (protocol),
    CONSTRAINT fk_sn_reports_owner FOREIGN KEY (owner_id) REFERENCES sn_users (id),
    CONSTRAINT fk_sn_reports_sensor FOREIGN KEY (sensor_id) REFERENCES sn_sensors (id),
    CONSTRAINT fk_sn_reports_photo FOREIGN KEY (photo_file_id) REFERENCES sn_files (id),
    CONSTRAINT fk_sn_reports_previous FOREIGN KEY (previous_report_id) REFERENCES sn_reports (id),
    CONSTRAINT ck_sn_reports_status CHECK (report_status IN ('RECEIVED', 'IN_PROGRESS', 'CLOSED'))
);
CREATE INDEX ix_sn_reports_owner ON sn_reports (owner_id, created_at);
CREATE INDEX ix_sn_reports_status ON sn_reports (report_status);

CREATE TABLE sn_report_updates (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    report_id      NUMBER(19)      NOT NULL,
    author_id      NUMBER(19)      NOT NULL,
    note           NVARCHAR2(600),
    photo_file_id  NUMBER(19),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_sn_report_updates PRIMARY KEY (id),
    CONSTRAINT fk_sn_updates_report FOREIGN KEY (report_id) REFERENCES sn_reports (id),
    CONSTRAINT fk_sn_updates_author FOREIGN KEY (author_id) REFERENCES sn_users (id),
    CONSTRAINT fk_sn_updates_photo FOREIGN KEY (photo_file_id) REFERENCES sn_files (id)
);

CREATE TABLE sn_report_history (
    id             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    report_id      NUMBER(19)      NOT NULL,
    entry_type     NVARCHAR2(30)   NOT NULL,
    actor_name     NVARCHAR2(120)  NOT NULL,
    from_value     NVARCHAR2(80),
    to_value       NVARCHAR2(80),
    message        NVARCHAR2(1000),
    internal_only  NUMBER(1)       NOT NULL,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_sn_report_history PRIMARY KEY (id),
    CONSTRAINT fk_sn_history_report FOREIGN KEY (report_id) REFERENCES sn_reports (id)
);
CREATE INDEX ix_sn_history_report ON sn_report_history (report_id, created_at);

CREATE TABLE sn_notifications (
    id                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    recipient_user_id  NUMBER(19),
    recipient_role     NVARCHAR2(20),
    notification_type  NVARCHAR2(40)   NOT NULL,
    title              NVARCHAR2(120)  NOT NULL,
    body               NVARCHAR2(600)  NOT NULL,
    reference_id       NVARCHAR2(40),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    read_at            TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_sn_notifications PRIMARY KEY (id)
);
CREATE INDEX ix_sn_notif_user ON sn_notifications (recipient_user_id, created_at);
CREATE INDEX ix_sn_notif_role ON sn_notifications (recipient_role, created_at);

CREATE TABLE sn_alert_recipients (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    full_name   NVARCHAR2(120)  NOT NULL,
    email       NVARCHAR2(160)  NOT NULL,
    active      NUMBER(1)       NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_sn_alert_recipients PRIMARY KEY (id),
    CONSTRAINT uk_sn_alert_recipients_email UNIQUE (email)
);

CREATE TABLE sn_email_logs (
    id               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    recipient        NVARCHAR2(160),
    subject          NVARCHAR2(200)  NOT NULL,
    event_type       NVARCHAR2(40)   NOT NULL,
    reference_id     NVARCHAR2(40),
    delivery_status  NVARCHAR2(20)   NOT NULL,
    error_message    NVARCHAR2(500),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_sn_email_logs PRIMARY KEY (id),
    CONSTRAINT ck_sn_email_logs_status CHECK (delivery_status IN ('SENT', 'FAILED', 'SKIPPED'))
);
CREATE INDEX ix_sn_email_logs_created ON sn_email_logs (created_at);
